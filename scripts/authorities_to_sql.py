"""Turn data/authorities.csv into an idempotent SQL upsert (supabase/seed/authorities.sql).

The CSV in git is the source of truth; this file is what gets loaded into the
database. Re-run after every change to the CSV.

Usage:
    python3 scripts/authorities_to_sql.py
"""

import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "authorities.csv"
OUT = ROOT / "supabase" / "seed" / "authorities.sql"

COLUMNS = [
    "id", "office", "kind", "handles", "area", "phone_published", "phone_dial",
    "email", "website", "source_url", "page_last_updated", "fetched_on",
    "status", "verified_on", "notes",
]


def literal(column: str, value: str) -> str:
    if value == "":
        return "'{}'" if column == "handles" else "null"
    if column == "handles":
        items = ",".join('"' + item.replace('"', "") + '"' for item in value.split(";") if item)
        return "'{" + items.replace("'", "''") + "}'"
    if column in ("fetched_on", "verified_on"):
        return f"'{value}'::date"
    return "'" + value.replace("'", "''") + "'"


def main():
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    values = ",\n".join(
        "  (" + ", ".join(literal(c, row[c]) for c in COLUMNS) + ")" for row in rows
    )
    updates = ",\n  ".join(f"{c} = excluded.{c}" for c in COLUMNS if c != "id")
    sql = (
        "-- Generated by scripts/authorities_to_sql.py from data/authorities.csv. Do not edit by hand.\n"
        f"insert into public.authorities ({', '.join(COLUMNS)}) values\n{values}\n"
        f"on conflict (id) do update set\n  {updates};\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding="utf-8")
    print(f"{len(rows)} rows -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
